# return =  statement used to end aa function and send a 
#           result back to the caller

def add(x,y):
    z = x + y
    return z

def subtract(x,y):
    z = x - y
    return z

def multiply(x,y):
    z = x * y
    return z

def divide(x,y):
    z = x / y
    return z

print(add(1,2))
print(subtract(3,2))
print(multiply(3,1))
print(divide(6,2))